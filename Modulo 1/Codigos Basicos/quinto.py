# operadores artiméticos 
# + - soma
# - - subtrção 
# / - divisão 
# * - multiplicação
# % - resto de divisão
# ** - elevado
numero1 = float( imput("Digite o primeiro número:") )
numero2 = float( imput("Digite o segundo número: ") )
print(f"{numero1} + {numero2} = {numero1 + numero2}")
print(numero1 - numero2)
print(numero1 * numero2)
print(numero1 / numero2)
print(numero1 % numero2)
print(numero1 ** numero2)

